#!/usr/bin/env node
/** Validate actual pixels and emit Metro's static item asset lookup. */
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const partial = process.argv.includes('--partial');
const check = process.argv.includes('--check');
const definitions = require('../src/game/catalog/items.json').items;
const entries = {};
const hashes = new Set();
for (const id of Object.keys(definitions)) {
  const relative = `assets/items/${id}.png`;
  const file = path.join(root, relative);
  if (!fs.existsSync(file) && partial) continue;
  const data = fs.readFileSync(file);
  if (data.readUInt32BE(16) !== 64 || data.readUInt32BE(20) !== 64) throw new Error(`${id}: expected 64x64`);
  const pixels = execFileSync('convert', [file, '-depth', '8', 'RGBA:-']);
  let occupied = 0, transparent = 0, border = 0;
  for (let y = 0; y < 64; y++) for (let x = 0; x < 64; x++) {
    const alpha = pixels[(y * 64 + x) * 4 + 3];
    if (alpha === 0) transparent++;
    if (alpha >= 128) {
      occupied++;
      if (x === 0 || x === 63 || y === 0 || y === 63) border++;
    }
  }
  if (occupied < 80 || transparent < 300 || border > 0) throw new Error(`${id}: empty, opaque-background or clipped icon (${occupied}/${transparent}/${border})`);
  const provenance = JSON.parse(fs.readFileSync(path.join(root, `image-generation/items/v1/provenance/${id}.json`)));
  const sha256 = createHash('sha256').update(data).digest('hex');
  if (provenance.id !== id || provenance.icon_sha256 !== sha256) throw new Error(`${id}: icon provenance mismatch`);
  const pixelHash = createHash('sha256').update(pixels).digest('hex');
  if (hashes.has(pixelHash)) throw new Error(`${id}: duplicated icon pixels`);
  hashes.add(pixelHash);
  entries[id] = { file: relative, size: [64, 64], sha256 };
}
const typescript = '// Generated by scripts/bundle-item-icons.cjs; do not edit.\n' +
  'export const itemImages: Record<string, number> = {\n' + Object.keys(entries).map(id =>
    `  ${id}: require('../../assets/items/${id}.png'),`).join('\n') + '\n};\n';
const manifest = JSON.stringify({ schemaVersion: 1, icons: entries }, null, 2) + '\n';
for (const [name, value] of [['src/items/generated.ts', typescript], ['assets/items/catalog.json', manifest]]) {
  const file = path.join(root, name);
  if (check) {
    if (fs.readFileSync(file, 'utf8') !== value) throw new Error(`${name}: stale bundle`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, value);
  }
}
console.log(`Validated ${Object.keys(entries).length}/${Object.keys(definitions).length} 64x64 item icons${partial ? ' (partial development bundle)' : ''}.`);
